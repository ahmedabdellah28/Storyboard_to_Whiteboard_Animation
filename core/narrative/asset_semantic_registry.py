def get_asset_metadata(asset_id: str) -> AssetSemanticMetadata:
    """Retrieves semantic metadata for an asset ID, with sensible fallback."""
    raw = SECTION_06_ASSET_REGISTRY.get(asset_id)
    if raw:
        return AssetSemanticMetadata(asset_id=asset_id, **raw)
    return AssetSemanticMetadata(
        asset_id=asset_id,
        semantic_name=f"asset_{asset_id}",
        category="prop",
        tags=["needs_semantic_mapping"],
        identity_group="unclassified",
        variant_group="default",
        visual_role="accent",
    )
